/**
 * Fetch OSM boundaries once, simplify them, and commit the GeoJSON.
 *
 * Uses Nominatim polygon_geojson (1 request/second, identifying User-Agent).
 * Run: npm run boundaries
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { feature, featureCollection } from "@turf/helpers";
import union from "@turf/union";
import simplify from "@turf/simplify";
import bbox from "@turf/bbox";
import truncate from "@turf/truncate";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const userAgent = "theHaofTravelo/0.1 (thehaoftravelo.pages.dev; boundary snapshot)";
const referer = "https://thehaoftravelo.pages.dev";

const plan = JSON.parse(
  await readFile(path.join(root, "scripts/boundaries.json"), "utf8"),
);

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function lookupRelation(id) {
  const url = new URL("https://nominatim.openstreetmap.org/lookup");
  url.searchParams.set("osm_ids", `R${id}`);
  url.searchParams.set("format", "jsonv2");
  url.searchParams.set("polygon_geojson", "1");
  const response = await fetch(url, {
    headers: {
      "User-Agent": userAgent,
      Referer: referer,
      Accept: "application/json",
    },
  });
  if (!response.ok) {
    throw new Error(`Nominatim ${response.status} for relation/${id}`);
  }
  const rows = await response.json();
  const row = rows?.[0];
  if (!row?.geojson) {
    throw new Error(`No polygon for relation/${id}`);
  }
  return row;
}

function toFeature(geojson, properties) {
  return feature(geojson, properties);
}

async function buildCity(id, spec) {
  const parts = [];
  for (const relationId of spec.relations) {
    process.stdout.write(`  relation/${relationId}… `);
    const row = await lookupRelation(relationId);
    parts.push(
      toFeature(row.geojson, {
        osm: `relation/${relationId}`,
        name: row.name || spec.osmName,
      }),
    );
    const pts = JSON.stringify(row.geojson).length;
    console.log(`${row.geojson.type}, ~${Math.round(pts / 1024)}kb raw`);
    await sleep(1100);
  }

  let merged = parts[0];
  if (parts.length > 1) {
    merged = union(featureCollection(parts));
    if (!merged) throw new Error(`Union failed for ${id}`);
  }

  const simplified = simplify(merged, {
    tolerance: spec.tolerance ?? 0.0012,
    highQuality: true,
    mutate: false,
  });
  const trimmed = truncate(simplified, { precision: 5, mutate: true });
  const [west, south, east, north] = bbox(trimmed);
  trimmed.properties = {
    id,
    osm: spec.relations.map((relationId) => `relation/${relationId}`).join("+"),
    osmName: spec.osmName,
    note: spec.note,
  };
  return {
    feature: trimmed,
    bounds: {
      south: round(south),
      west: round(west),
      north: round(north),
      east: round(east),
      osm: trimmed.properties.osm,
      osmName: spec.osmName,
      note: spec.note,
    },
  };
}

function round(value) {
  return Math.round(value * 1e5) / 1e5;
}

const outDir = path.join(root, "web/public/boundaries");
await mkdir(outDir, { recursive: true });

const bounds = {};
const features = [];

for (const [id, spec] of Object.entries(plan)) {
  console.log(`\n${id}`);
  const result = await buildCity(id, spec);
  bounds[id] = result.bounds;
  features.push(result.feature);
  await writeFile(
    path.join(outDir, `${id}.geojson`),
    JSON.stringify(result.feature),
  );
  console.log(
    `  bbox ${result.bounds.south},${result.bounds.west},${result.bounds.north},${result.bounds.east}`,
  );
}

await writeFile(
  path.join(outDir, "cities.geojson"),
  JSON.stringify({ type: "FeatureCollection", features }),
);

const lines = [
  "// Generated by scripts/fetch-boundaries.mjs. Do not edit by hand.",
  "// Regenerate with: npm run boundaries",
  "// Map data © OpenStreetMap contributors, ODbL.",
  "",
  "export type CityBound = {",
  "  south: number;",
  "  west: number;",
  "  north: number;",
  "  east: number;",
  "  osm: string;",
  "  osmName: string;",
  "  note: string;",
  "};",
  "",
  `export const cityBounds = ${JSON.stringify(bounds, null, 2)} as const satisfies Record<string, CityBound>;`,
  "",
];
await writeFile(path.join(root, "shared/src/cityBounds.ts"), lines.join("\n"));
console.log(`\nWrote ${features.length} cities.`);
